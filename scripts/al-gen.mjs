// Generates the data codeunit of the "Kalvaert Demo Setup" app from data/case.json and the migration export.
// The AL compiler then checks every table, field and option name against the real Business Central symbols,
// so the solution design on paper and the setup in the sandbox cannot drift apart.
import { createHash } from "node:crypto";
import * as L from "../site/assets/case-logic.mjs";

const q = (s) => `'${String(s ?? "").replaceAll("'", "''")}'`;
const dec = (n) => (n == null ? "0" : Number(n).toFixed(2));
const bool = (b) => (b ? "true" : "false");

// Belgian enterprise numbers: 10 digits, the last two are 97 - (first eight mod 97). Fictitious but valid.
export function enterpriseNo(seed) {
  const base = 400000000 + (parseInt(createHash("sha1").update(seed).digest("hex").slice(0, 8), 16) % 99999999);
  const first8 = Math.floor(base / 100);
  const check = 97 - (first8 % 97);
  const digits = String(first8).padStart(8, "0") + String(check).padStart(2, "0");
  return `${digits.slice(0, 4)}.${digits.slice(4, 7)}.${digits.slice(7)}`;
}
export const validEnterpriseNo = (no) => {
  const d = no.replaceAll(".", "");
  return /^\d{10}$/.test(d) && 97 - (Number(d.slice(0, 8)) % 97) === Number(d.slice(8));
};

const COUNTRY = { BINNENL: "BE", EU: "FR", EXPORT: "CH" };
const LOCATIONS = [
  { code: "HQ", name: "Hoofdzetel en magazijn", inTransit: false },
  { code: "FILIAAL", name: "Filiaal met balie", inTransit: false },
  { code: "IN-TRANSIT", name: "Onderweg tussen de vestigingen", inTransit: true },
];

export function generateDemoData(caseData, migrationCsv, sources) {
  const s = caseData.setup;
  const control = new Set([
    ...s.customerPostingGroups.map((g) => g.receivables),
    ...s.vendorPostingGroups.map((g) => g.payables),
    ...s.inventoryPostingSetup.map((p) => p.inventory),
  ]);
  const feeSetup = s.generalPostingSetup.find((g) => g.prod === "BIJDRAGE");
  const vatProd = s.vatProdPostingGroups[0].code;
  const out = [];
  const line = (t = "") => out.push(t);
  const call = (proc, ...args) => line(`        H.${proc}(${args.join(", ")});`);

  line("// Generated by scripts/build.mjs (scripts/al-gen.mjs) from data/case.json and the migration export. Do not edit by hand.");
  line("namespace Kalvaert.DemoSetup;");
  line();
  line("using Microsoft.Sales.Customer;");
  line();
  line("codeunit 50204 \"KLV Demo Data\"");
  line("{");
  line("    Access = Internal;");
  line();
  line("    procedure DataVersion(): Text[40]");
  line("    begin");
  line(`        exit(${q(createHash("sha256").update(sources).digest("hex").slice(0, 12))});`);
  line("    end;");
  line();
  line("    procedure ApplySetup(var H: Codeunit \"KLV Demo Helpers\")");
  line("    begin");
  line("        // VAT and general posting groups (SET-GENPOST, SET-GENPROD, SET-BTW)");
  for (const g of s.vatBusPostingGroups) call("EnsureVATBusGroup", q(g.code), q(g.description));
  for (const g of s.vatProdPostingGroups) call("EnsureVATProdGroup", q(g.code), q(g.description));
  for (const g of s.genBusPostingGroups) call("EnsureGenBusGroup", q(g.code), q(g.description), q(g.code));
  for (const g of s.genProdPostingGroups) call("EnsureGenProdGroup", q(g.code), q(g.description), q(vatProd));
  line();
  line("        // chart of accounts, extract (SET-REKENINGEN, FIN-01)");
  for (const a of s.accounts) {
    const isFee = feeSetup && a.no === feeSetup.sales;
    call("EnsureGLAccount", q(a.no), q(a.name), bool(/^[67]/.test(a.no)), bool(!control.has(a.no)), bool(isFee), q(isFee ? "BIJDRAGE" : ""), q(isFee ? vatProd : ""));
  }
  line();
  line("        // VAT posting setup with clauses on exempt lines (SET-BTW, FIN-02)");
  for (const v of s.vatPostingSetup) {
    const clause = v.clause ? `VRIJ-${v.bus}` : "";
    if (clause) call("EnsureVATClause", q(clause), q(v.clause));
    const reverse = v.calc === "Btw verleggen";
    const identifier = reverse ? `VERL${v.pct}` : v.pct === 0 ? `VRIJ${v.bus}` : `${v.pct}`;
    call("EnsureVATPostingSetup", q(v.bus), q(v.prod), bool(reverse), dec(v.pct), q(identifier.slice(0, 20)), q(v.salesVat), q(v.purchVat), q(v.reverseChrg ?? ""), q(clause));
  }
  line();
  line("        // general posting setup; the blank business group is used by item journals and transfers");
  for (const g of s.generalPostingSetup) call("EnsureGenPostingSetup", q(g.bus), q(g.prod), q(g.sales), q(g.purchase), q(g.cogs ?? ""));
  const cogs = s.generalPostingSetup.find((g) => g.prod === "HANDELSGOED")?.cogs ?? "";
  call("EnsureGenPostingSetup", q(""), q("HANDELSGOED"), q(""), q(""), q(cogs));
  for (const g of s.customerPostingGroups) call("EnsureCustomerPostingGroup", q(g.code), q(g.receivables));
  for (const g of s.vendorPostingGroups) call("EnsureVendorPostingGroup", q(g.code), q(g.payables));
  line();
  line("        // locations, transfer route and inventory posting (SET-LOCATIES, VR-01)");
  for (const l of LOCATIONS) call("EnsureLocation", q(l.code), q(l.name), bool(l.inTransit));
  call("EnsureTransferRoute", q("HQ"), q("FILIAAL"), q("IN-TRANSIT"));
  call("EnsureTransferRoute", q("FILIAAL"), q("HQ"), q("IN-TRANSIT"));
  call("EnsureInventoryPostingGroup", q("HANDELSGOED"), q("Handelsgoederen"));
  const invAcc = s.inventoryPostingSetup[0].inventory;
  for (const p of s.inventoryPostingSetup) call("EnsureInventoryPostingSetup", q(p.location), q(p.group), q(p.inventory));
  call("EnsureInventoryPostingSetup", q("IN-TRANSIT"), q("HANDELSGOED"), q(invAcc));
  call("EnsureInventoryPostingSetup", q(""), q("HANDELSGOED"), q(invAcc));
  line();
  line("        // payment (SET-BETWIJZE, VK-03, VK-05)");
  call("EnsurePaymentTerms", q("30D"), q("30 dagen"), q("<30D>"));
  call("EnsurePaymentTerms", q("VOORAF"), q("Vooraf betalen"), q("<0D>"));
  for (const p of s.paymentMethods) call("EnsurePaymentMethod", q(p.code), q(p.description), q(p.balancingAccount ?? ""));
  line();
  line("        // dimensions (SET-DIM, FIN-04)");
  for (const d of s.dimensions) {
    call("EnsureDimension", q(d.code), q(d.code[0] + d.code.slice(1).toLowerCase()));
    for (const v of d.values) call("EnsureDimensionValue", q(d.code), q(v), q(v));
  }
  const [g1, g2] = [...s.dimensions].sort((a, b) => a.global - b.global).map((d) => d.code);
  line(`        if not H.SetGlobalDimensions(${q(g1)}, ${q(g2)}) then`);
  line("            ; // the company already has other global dimensions: use Change Global Dimensions, see bc/README.md");
  for (const d of s.dimensions) {
    for (const m of d.rule.matchAll(/(\d{6})(?:\s*[–-]\s*(\d{6}))?/g)) call("RequireDimensionOnAccounts", q(m[1]), q(m[2] ?? m[1]), q(d.code));
  }
  line();
  line("        // items (VK-10: the fee per unit is a field on the item)");
  call("EnsureUnitOfMeasure", q("STUK"), q("Stuk"));
  for (const i of s.items) {
    const inventory = i.genProd === "HANDELSGOED";
    call("EnsureItem", q(i.no), q(i.description), bool(inventory), q(i.genProd), q(i.vatProd), q(inventory ? "HANDELSGOED" : ""), dec(i.unitPrice), dec(i.unitCost), dec(i.contribution), q("STUK"));
  }
  line();
  line("        // customer templates (SET-KLANTSJABLOON, VK-05, EF-03)");
  call("EnsureCustomerTemplate", q("NIEUW"), q("Nieuwe klant: kredietlimiet, vooraf betalen"), q("BINNENL"), q("BINNENL"), q("BINNENL"), dec(NEW_CUSTOMER_CREDIT_LIMIT), q("VOORAF"), q("OVERSCHR"));
  call("EnsureCustomerTemplate", q("BINNENL"), q("Klant in België"), q("BINNENL"), q("BINNENL"), q("BINNENL"), dec(0), q("30D"), q("OVERSCHR"));
  call("EnsureCustomerTemplate", q("EU"), q("Btw-plichtige klant in een andere EU-lidstaat"), q("EU"), q("EU"), q("BUITENL"), dec(0), q("30D"), q("OVERSCHR"));
  call("EnsureCustomerTemplate", q("EXPORT"), q("Klant buiten de EU"), q("EXPORT"), q("EXPORT"), q("BUITENL"), dec(0), q("VOORAF"), q("OVERSCHR"));
  line();
  line("        // customers: the four from the solution design, plus every customer with an open entry (MIG-02)");
  const customers = customerList(caseData, migrationCsv);
  for (const c of customers) {
    call("EnsureCustomer", q(c.no), q(c.name), q(c.genBus), q(c.vatBus), q(c.postingGroup), q(c.paymentMethod), q(c.paymentTerms), q(c.location), q(COUNTRY[c.genBus]), q(c.enterpriseNo), q(c.vatRegNo));
    if (c.vestiging) call("SetDefaultDimension", "Database::Customer", q(c.no), q("VESTIGING"), q(c.vestiging), "false");
    if (c.afdeling) call("SetDefaultDimension", "Database::Customer", q(c.no), q("AFDELING"), q(c.afdeling), "false");
  }
  line();
  line("        // the only extension (VK-10)");
  call("ConfigureRemovalFee", q("BINNENL"), q(feeSetup.sales), q("BIJDRAGE"), q("Verwijderingsbijdrage %1"));
  line("    end;");
  line();
  line("    procedure OpenCustomerEntries(var M: Codeunit \"KLV Demo Migration\")");
  line("    begin");
  for (const r of L.parseCsv(migrationCsv)) {
    line(`        M.AddEntry(${bool(r.documenttype === "Creditnota")}, ${q(r.documentnr)}, ${q(r.klantnr)}, ${Number(r.dagen_voor_cutoff)}, ${dec(r.openstaand_bedrag)});`);
  }
  line("    end;");
  line("}");
  return { code: out.join("\n") + "\n", customers };
}

// VK-05: in Business Central a credit limit of 0 means "no limit", so "credit limit 0" for new customers is set as €1.
export const NEW_CUSTOMER_CREDIT_LIMIT = 1;

export function customerList(caseData, migrationCsv) {
  const s = caseData.setup;
  const known = new Map(s.customers.map((c) => [c.no, c]));
  const rows = L.parseCsv(migrationCsv);
  const list = [];
  const add = (c) => {
    const domestic = c.genBus === "BINNENL";
    list.push({
      ...c,
      paymentTerms: c.paymentMethod === "CONTANT" ? "VOORAF" : "30D",
      enterpriseNo: domestic ? enterpriseNo(c.no) : "",
      vatRegNo: c.genBus === "EU" ? `FR${String(parseInt(createHash("sha1").update(c.no).digest("hex").slice(0, 9), 16) % 1e11).padStart(11, "0")}` : domestic ? `BE${enterpriseNo(c.no).replaceAll(".", "")}` : "",
    });
  };
  for (const c of s.customers) add({ no: c.no, name: c.description, genBus: c.genBus, vatBus: c.vatBus, postingGroup: c.postingGroup, paymentMethod: c.paymentMethod, location: c.location, vestiging: c.location, afdeling: c.afdeling });
  for (const no of [...new Set(rows.map((r) => r.klantnr))]) {
    if (known.has(no)) continue;
    const foreign = rows.find((r) => r.klantnr === no).rekening === "400100";
    add({ no, name: `Klant ${no} (fictief, uit de migratie)`, genBus: foreign ? "EU" : "BINNENL", vatBus: foreign ? "EU" : "BINNENL", postingGroup: foreign ? "BUITENL" : "BINNENL", paymentMethod: "OVERSCHR", location: "HQ", vestiging: "HQ", afdeling: "BINNENDIENST" });
  }
  return list;
}
